#!/usr/bin/env python3
"""Roll up results/<model>/*.jsonl into the committed BENCHMARKS.md summary.

Raw per-run artifacts stay gitignored under results/; this distills the latest
verdict per (case, model) into one human-readable table so the value history is
visible in git without the heavy artifacts. Compare numbers only within one
EVAL_SET_VERSION — when the case mix changes, bump it (see PLAYBOOK.md).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

EVALS_DIR = Path(__file__).resolve().parent
RESULTS_DIR = EVALS_DIR / "results"
BENCH_DIR = RESULTS_DIR / "bench"
OUT = EVALS_DIR / "BENCHMARKS.md"
EVAL_SET_VERSION = "v1"


def _latest_per_case_model() -> dict[tuple[str, str], dict]:
    """Keep the most recent artifact for each (id, model); filename starts with the date."""
    latest: dict[tuple[str, str], tuple[str, dict]] = {}
    if not RESULTS_DIR.exists():
        return {}
    for path in RESULTS_DIR.glob("*/*.jsonl"):
        try:
            rec = json.loads(path.read_text("utf-8").strip().splitlines()[-1])
        except (json.JSONDecodeError, IndexError):
            continue
        key = (rec.get("id", "?"), rec.get("model", path.parent.name))
        stamp = path.name  # ISO date prefix sorts lexicographically
        if key not in latest or stamp > latest[key][0]:
            latest[key] = (stamp, rec)
    return {k: v[1] for k, v in latest.items()}


def _eff_delta(rec: dict) -> str:
    """Mean treatment−control tool-call delta across runs (negative ⇒ leaner)."""
    runs = rec.get("runs", [])
    if not runs:
        return "—"
    deltas = [r["treatment"]["tool_calls"] - r["control"]["tool_calls"]
              for r in runs if "treatment" in r and "control" in r]
    if not deltas:
        return "—"
    return f"{sum(deltas) / len(deltas):+.1f}"


def _load_bench() -> list[dict]:
    if not BENCH_DIR.exists():
        return []
    out = []
    for path in sorted(BENCH_DIR.glob("*.json")):
        try:
            out.append(json.loads(path.read_text("utf-8").strip().splitlines()[-1]))
        except (json.JSONDecodeError, IndexError):
            continue
    return out


def _render_bench(benches: list[dict]) -> list[str]:
    if not benches:
        return []
    lines = [
        "## Deterministic tool benchmarks",
        "",
        "Concrete, model-independent measurements for tools whose value is a fixed",
        "transform (compression, structural precision, code-graph extraction) rather",
        "than an agent choice. No LLM judge, no tokens spent. Generated by",
        "`evals/bench.py`; numbers are absolute.",
        "",
    ]
    comp = [b for b in benches if b["kind"] == "compression"]
    if comp:
        lines += [
            "### Output compression (bytes / approx tokens, baseline → tool)",
            "",
            "| Tool | Benchmark | Baseline bytes | Tool bytes | Baseline ~tok | Tool ~tok | Reduction |",
            "|------|-----------|----------------|------------|---------------|-----------|-----------|",
        ]
        for b in comp:
            base, tool = b["baseline"], b["tool"]
            factor = b.get("reduction_factor")
            red = f"{b.get('reduction_pct', 0)}% (×{factor:,.0f})" if factor else f"{b.get('reduction_pct', 0)}%"
            lines.append(
                f"| {b['tool_name']} | {b['label']} | {base['bytes']:,} | {tool['bytes']:,} | "
                f"{base['approx_tokens']:,} | {tool['approx_tokens']:,} | {red} |"
            )
        lines.append("")
    prec = [b for b in benches if b["kind"] == "precision"]
    if prec:
        lines += [
            "### Structural precision (matches, false positives)",
            "",
            "| Tool | Benchmark | True matches | grep matches (FP) | tool matches (FP) |",
            "|------|-----------|--------------|-------------------|-------------------|",
        ]
        for b in prec:
            base, tool = b["baseline"], b["tool"]
            lines.append(
                f"| {b['tool_name']} | {b['label']} | {b['true_matches']} | "
                f"{base['matches']} ({base['false_positives']} FP) | "
                f"{tool['matches']} ({tool['false_positives']} FP) |"
            )
        lines.append("")
    graph = [b for b in benches if b["kind"] == "graph"]
    if graph:
        lines += [
            "### Code-graph extraction (structure grep cannot give)",
            "",
            "| Tool | Benchmark | grep text matches | nodes | edges | clusters | flows | index ms |",
            "|------|-----------|-------------------|-------|-------|----------|-------|----------|",
        ]
        for b in graph:
            base, tool = b["baseline"], b["tool"]
            lines.append(
                f"| {b['tool_name']} | {b['label']} | {base['text_matches']} | {tool.get('nodes','?')} | "
                f"{tool.get('edges','?')} | {tool.get('clusters','?')} | {tool.get('flows','?')} | "
                f"{tool.get('index_ms','?')} |"
            )
        lines.append("")
    return lines


def render(records: dict[tuple[str, str], dict], benches: list[dict] | None = None) -> str:
    lines = [
        "# Benchmark results",
        "",
        f"Eval-set version: **{EVAL_SET_VERSION}**. Compare numbers only within the same",
        "version (the case mix changes between versions). Generated by `evals/report.py`",
        "from `results/`; do not edit by hand.",
        "",
        "## Value A/B uplift (agent outcome, per model)",
        "",
    ]
    if not records:
        lines += ["_No value A/B results recorded yet._ Run:", "",
                  "```bash",
                  "AGENTIC_EVAL_CONFIRM=1 python3 evals/run.py --track value --model <model>",
                  "python3 evals/report.py",
                  "```", ""]
    else:
        lines += [
            "| Case | Model | Verdict | Treatment wins | Flip-rate | Tool-call Δ | Confidence |",
            "|------|-------|---------|----------------|-----------|-------------|------------|",
        ]
        for (cid, model), rec in sorted(records.items()):
            wins = rec.get("wins", {})
            n = rec.get("n", 0) or 1
            share = f"{wins.get('treatment', 0)}/{n}"
            lines.append(
                f"| {cid} | {model} | {rec.get('verdict', '?')} | {share} | "
                f"{rec.get('flip_rate', 0):.2f} | {_eff_delta(rec)} | {rec.get('confidence', '?')} |"
            )
        lines.append("")

    lines += _render_bench(benches or [])
    return "\n".join(lines)


def main() -> int:
    content = render(_latest_per_case_model(), _load_bench())
    OUT.write_text(content, "utf-8")
    print(f"wrote {OUT.relative_to(EVALS_DIR.parent)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
