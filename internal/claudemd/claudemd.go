// Package claudemd ports providers/shared/merge-claude-md.py: it ensures the
// user's CLAUDE.md imports the repo-managed generated config through a small
// managed @import block, preserving any hand-written user content (PORT-01).
package claudemd

import (
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

const (
	begin           = "<!-- BEGIN agentic-cfg (managed) -->"
	end             = "<!-- END agentic-cfg (managed) -->"
	legacySignature = "<!-- Generated by agentic bin/install.sh"
)

var blockRe = regexp.MustCompile(`(?s)` + regexp.QuoteMeta(begin) + `.*?` + regexp.QuoteMeta(end))

// Render returns the new CLAUDE.md content for the given existing content and the
// absolute path of the generated file to import.
func Render(existing, generatedAbs string) string {
	block := begin + "\n@" + generatedAbs + "\n" + end
	switch {
	case blockRe.MatchString(existing):
		return blockRe.ReplaceAllLiteralString(existing, block) // refresh managed block
	case strings.HasPrefix(strings.TrimLeft(existing, " \t\r\n"), legacySignature):
		return block + "\n" // migrate a legacy fully-generated file
	case strings.TrimSpace(existing) != "":
		return strings.TrimRight(existing, "\n") + "\n\n" + block + "\n" // keep user content
	default:
		return block + "\n"
	}
}

// Ensure writes or updates claudeMdPath so it imports generatedPath, preserving
// any pre-existing user content.
func Ensure(generatedPath, claudeMdPath string) error {
	abs, err := filepath.Abs(generatedPath)
	if err != nil {
		abs = generatedPath
	}
	existing := ""
	if b, err := os.ReadFile(claudeMdPath); err == nil {
		existing = string(b)
	}
	if err := os.MkdirAll(filepath.Dir(claudeMdPath), 0o755); err != nil {
		return err
	}
	// G306: CLAUDE.md is non-secret user config; 0644 matches the install convention.
	return os.WriteFile(claudeMdPath, []byte(Render(existing, abs)), 0o644) //nolint:gosec // non-secret user config; 0644 is intentional
}
