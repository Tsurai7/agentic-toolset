#!/usr/bin/env python3
"""Ensure ~/.claude/CLAUDE.md imports the repo-managed generated config.

The repo writes its full instruction block to a separate generated file and keeps
only a small managed `@import` block inside the user's CLAUDE.md, so hand-written
user content in CLAUDE.md is preserved across installs (PORT-01). Claude Code
expands `@path` imports into context identically to inline content.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

BEGIN = "<!-- BEGIN agentic-cfg (managed) -->"
END = "<!-- END agentic-cfg (managed) -->"
# Prefix the legacy installer wrote straight into CLAUDE.md. An existing file
# starting with it is a fully-generated legacy file, safe to replace wholesale
# (its content now lives in the imported generated file instead).
LEGACY_SIGNATURE = "<!-- Generated by agentic bin/install.sh"


def render(existing: str, generated: Path) -> str:
    block = f"{BEGIN}\n@{generated}\n{END}"
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.DOTALL)
    if pattern.search(existing):
        return pattern.sub(lambda _: block, existing)  # refresh managed block
    if existing.lstrip().startswith(LEGACY_SIGNATURE):
        return block + "\n"  # migrate a legacy fully-generated file
    if existing.strip():
        return existing.rstrip("\n") + "\n\n" + block + "\n"  # keep user content
    return block + "\n"


def main() -> int:
    if len(sys.argv) < 3:
        print("Usage: merge-claude-md.py <generated_file> <claude_md>", file=sys.stderr)
        return 1
    generated = Path(sys.argv[1]).resolve()
    target = Path(sys.argv[2])
    existing = target.read_text(encoding="utf-8") if target.is_file() else ""
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render(existing, generated), encoding="utf-8")
    print(f"agentic-cfg @import ensured in {target} -> {generated}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
